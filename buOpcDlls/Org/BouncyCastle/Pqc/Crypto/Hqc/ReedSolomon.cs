  private static int ComputeELP(int[] sigma, int[] syndromes, int delta)
  {
    sigma[0] = 1;
    int elp = 0;
    int num1 = 0;
    int[] destinationArray = new int[delta + 1];
    int[] numArray = new int[delta + 1];
    int unsigned16Bits1 = Utils.ToUnsigned16Bits(-1);
    int a1 = 1;
    int syndrome = syndromes[0];
    numArray[1] = 1;
    for (int index1 = 0; index1 < 2 * delta; ++index1)
    {
      Array.Copy((Array) sigma, 0, (Array) destinationArray, 0, delta + 1);
      int num2 = elp;
      int a2 = GFCalculator.mult(syndrome, GFCalculator.inverse(a1));
      for (int index2 = 1; index2 <= index1 + 1 && index2 <= delta; ++index2)
        sigma[index2] ^= GFCalculator.mult(a2, numArray[index2]);
      int unsigned16Bits2 = Utils.ToUnsigned16Bits(Utils.ToUnsigned16Bits(index1 - unsigned16Bits1) + num1);
      int num3 = (syndrome != 0 ? (int) ushort.MaxValue : 0) & (unsigned16Bits2 > elp ? (int) ushort.MaxValue : 0);
      elp ^= num3 & (unsigned16Bits2 ^ elp);
      if (index1 != 2 * delta - 1)
      {
        unsigned16Bits1 ^= num3 & (index1 ^ unsigned16Bits1);
        a1 ^= num3 & (syndrome ^ a1);
        for (int index3 = delta; index3 > 0; --index3)
          numArray[index3] = num3 & destinationArray[index3 - 1] ^ ~num3 & numArray[index3 - 1];
        num1 ^= num3 & (num2 ^ num1);
        syndrome = syndromes[index1 + 1];
        for (int index4 = 1; index4 <= index1 + 1 && index4 <= delta; ++index4)
          syndrome ^= GFCalculator.mult(sigma[index4], syndromes[index1 + 1 - index4]);
      }
      else
        break;
    }
    return elp;
  }

  private static void ComputeZx(int[] output, int[] sigma, int deg, int[] syndromes, int delta)
  {
    output[0] = 1;
    for (int index = 1; index < delta + 1; ++index)
    {
      int maxValue = index - deg < 1 ? (int) ushort.MaxValue : 0;
      output[index] = maxValue & sigma[index];
    }
    output[1] ^= syndromes[0];
    for (int index1 = 2; index1 <= delta; ++index1)
    {
      int maxValue = index1 - deg < 1 ? (int) ushort.MaxValue : 0;
      output[index1] = maxValue & sigma[index1 - 1];
      for (int index2 = 1; index2 < index1; ++index2)
        output[index1] ^= maxValue & GFCalculator.mult(sigma[index2], syndromes[index1 - index2 - 1]);
    }
  }

