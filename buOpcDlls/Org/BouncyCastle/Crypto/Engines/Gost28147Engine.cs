  public virtual void Init(bool forEncryption, ICipherParameters parameters)
  {
    switch (parameters)
    {
      case ParametersWithSBox parametersWithSbox:
        byte[] sbox = parametersWithSbox.GetSBox();
        if (sbox.Length != Gost28147Engine.Sbox_Default.Length)
          throw new ArgumentException("invalid S-box passed to GOST28147 init");
        this.S = Arrays.Clone(sbox);
        if (parametersWithSbox.Parameters == null)
          break;
        this.workingKey = this.GenerateWorkingKey(forEncryption, ((KeyParameter) parametersWithSbox.Parameters).GetKey());
        break;
      case KeyParameter keyParameter:
        this.workingKey = this.GenerateWorkingKey(forEncryption, keyParameter.GetKey());
        break;
      case null:
        break;
      default:
        throw new ArgumentException("invalid parameter passed to Gost28147 init - " + Platform.GetTypeName((object) parameters));
    }
  }

  public virtual string AlgorithmName => "Gost28147";

  public virtual int GetBlockSize() => 8;

  public virtual int ProcessBlock(byte[] input, int inOff, byte[] output, int outOff)
  {
    if (this.workingKey == null)
      throw new InvalidOperationException("Gost28147 engine not initialised");
    Org.BouncyCastle.Crypto.Check.DataLength(input, inOff, 8, "input buffer too short");
    Org.BouncyCastle.Crypto.Check.OutputLength(output, outOff, 8, "output buffer too short");
    this.Gost28147Func(this.workingKey, input, inOff, output, outOff);
    return 8;
  }

  private int[] GenerateWorkingKey(bool forEncryption, byte[] userKey)
  {
    this.forEncryption = forEncryption;
    if (userKey.Length != 32 /*0x20*/)
      throw new ArgumentException("Key length invalid. Key needs to be 32 byte - 256 bit!!!");
    int[] workingKey = new int[8];
    for (int index = 0; index != 8; ++index)
      workingKey[index] = (int) Pack.LE_To_UInt32(userKey, index * 4);
    return workingKey;
  }

  private int Gost28147_mainStep(int n1, int key)
  {
    int num1 = key + n1;
    int num2 = (int) this.S[num1 & 15] + ((int) this.S[16 /*0x10*/ + (num1 >> 4 & 15)] << 4) + ((int) this.S[32 /*0x20*/ + (num1 >> 8 & 15)] << 8) + ((int) this.S[48 /*0x30*/ + (num1 >> 12 & 15)] << 12) + ((int) this.S[64 /*0x40*/ + (num1 >> 16 /*0x10*/ & 15)] << 16 /*0x10*/) + ((int) this.S[80 /*0x50*/ + (num1 >> 20 & 15)] << 20) + ((int) this.S[96 /*0x60*/ + (num1 >> 24 & 15)] << 24) + ((int) this.S[112 /*0x70*/ + (num1 >> 28 & 15)] << 28);
    return num2 << 11 | num2 >>> 21;
  }

  private void Gost28147Func(
    int[] workingKey,
    byte[] inBytes,
    int inOff,
    byte[] outBytes,
    int outOff)
  {
    int num1 = (int) Pack.LE_To_UInt32(inBytes, inOff);
    int num2 = (int) Pack.LE_To_UInt32(inBytes, inOff + 4);
    if (this.forEncryption)
    {
      for (int index1 = 0; index1 < 3; ++index1)
      {
        for (int index2 = 0; index2 < 8; ++index2)
        {
          int num3 = num1;
          int num4 = this.Gost28147_mainStep(num1, workingKey[index2]);
          num1 = num2 ^ num4;
          num2 = num3;
        }
      }
      for (int index = 7; index > 0; --index)
      {
        int num5 = num1;
        num1 = num2 ^ this.Gost28147_mainStep(num1, workingKey[index]);
        num2 = num5;
      }
    }
    else
    {
      for (int index = 0; index < 8; ++index)
      {
        int num6 = num1;
        num1 = num2 ^ this.Gost28147_mainStep(num1, workingKey[index]);
        num2 = num6;
      }
      for (int index3 = 0; index3 < 3; ++index3)
      {
        for (int index4 = 7; index4 >= 0 && (index3 != 2 || index4 != 0); --index4)
        {
          int num7 = num1;
          num1 = num2 ^ this.Gost28147_mainStep(num1, workingKey[index4]);
          num2 = num7;
        }
      }
    }
    int n = num2 ^ this.Gost28147_mainStep(num1, workingKey[0]);
    Pack.UInt32_To_LE((uint) num1, outBytes, outOff);
    Pack.UInt32_To_LE((uint) n, outBytes, outOff + 4);
  }

  public static byte[] GetSBox(string sBoxName)
  {
    byte[] data;
    if (!Gost28147Engine.m_sBoxes.TryGetValue(sBoxName, out data))
      throw new ArgumentException("Unknown S-Box - possible types: \"Default\", \"E-Test\", \"E-A\", \"E-B\", \"E-C\", \"E-D\", \"D-Test\", \"D-A\".");
    return Arrays.Clone(data);
  }

  public static string GetSBoxName(byte[] sBox)
  {
    foreach (KeyValuePair<string, byte[]> sBox1 in Gost28147Engine.m_sBoxes)
    {
      if (Arrays.AreEqual(sBox1.Value, sBox))
        return sBox1.Key;
    }
    throw new ArgumentException("SBOX provided did not map to a known one");
  }
