	private void btn_minimize_Click(object sender, EventArgs e)
	{
		base.WindowState = FormWindowState.Minimized;
	}

	private void btn_maximize_Click(object sender, EventArgs e)
	{
		if (base.WindowState != FormWindowState.Maximized)
		{
			base.WindowState = FormWindowState.Maximized;
		}
		else
		{
			base.WindowState = FormWindowState.Normal;
		}
	}

	public void btn_close_Click(object sender, EventArgs e)
	{
		try
		{
			if (clsVar.varRuntime.MachineID == 31)
			{
				if (clsAppMarbleVars.cMachine.runSystem.Run)
				{
					F_Intro.appMachine3Milling.ShowWarning(buLangTranslate.preMotionWarning.SystemisRunning, Color.Gold);
				}
				else if (clsAppMarbleVars.cMachine.runSystem.Pause)
				{
					F_Intro.appMachine3Milling.ShowWarning(buLangTranslate.preMotionWarning.SsytemisPaused, Color.Gold);
				}
				else
				{
					clsLocalCommand.Exit();
				}
			}
		}
		catch (Exception)
		{
		}
	}

	private void spn_Enter(object sender, EventArgs e)
	{
		buSpin buSpin2 = sender as buSpin;
		buSpin2.Display.BackColor = buEyeVars.parVisual.colorDataFocus;
		buSpin2.SelectAll();
	}

	public void spn_Leave(object sender, EventArgs e)
	{
		buSpin buSpin2 = sender as buSpin;
	}

	private void spn_ValueClicked(object sender, EventArgs e)
	{
		buSpin buSpin2 = sender as buSpin;
		if (AppBool.TouchPad)
		{
			F_KeyPadNumV1 f_KeyPadNumV = new F_KeyPadNumV1();
			f_KeyPadNumV.StartPosition = FormStartPosition.CenterParent;
			f_KeyPadNumV.Caption = buSpin2.Caption.Caption;
			f_KeyPadNumV.ShowDialog(buSpin2.Value.ToString());
			if (buNumeric5.IsNumeric(f_KeyPadNumV.Value))
			{
				buSpin2.Value = double.Parse(f_KeyPadNumV.Value);
			}
		}
	}

	private void lbl_warning_Click(object sender, EventArgs e)
	{
		lbl_warning.Visible = false;
	}

