	public override string EncodingName => "WinAnsiEncoding";

	private WinAnsiEncoding()
	{
		(int, string)[] encodingTable = EncodingTable;
		for (int i = 0; i < encodingTable.Length; i++)
		{
			(int, string) tuple = encodingTable[i];
			int item = tuple.Item1;
			string item2 = tuple.Item2;
			int code = Convert.ToInt32($"{item}", 8);
			Add(code, item2);
		}
		for (int j = 41; j <= 255; j++)
		{
			if (!CodeToName.ContainsKey(j))
			{
				Add(j, "bullet");
			}
		}
	}
