$ErrorActionPreference = 'Continue'
New-Item -ItemType Directory -Force build-logs | Out-Null
$out = 'build-logs/dependency-audit.txt'
Remove-Item $out -ErrorAction Ignore

$projects = @(Get-ChildItem -Recurse -Filter *.csproj -File)
$missing = New-Object System.Collections.Generic.List[string]
$managed = New-Object System.Collections.Generic.List[object]
$hintCount = 0

"CAD/CAM dependency audit" | Tee-Object $out
"Projects: $($projects.Count)" | Tee-Object -Append $out

foreach ($project in $projects) {
    "`n===== $($project.FullName) =====" | Add-Content $out
    try {
        [xml]$xml = [IO.File]::ReadAllText($project.FullName)

        # Namespace-agnostic XPath works for both old MSBuild XML projects and
        # SDK-style projects generated by decompilers.
        $nodes = @($xml.SelectNodes('//*[local-name()="Reference" and *[local-name()="HintPath"]]'))
        foreach ($ref in $nodes) {
            $hintNode = $ref.SelectSingleNode('./*[local-name()="HintPath"]')
            if ($null -eq $hintNode) { continue }
            $hint = [string]$hintNode.InnerText
            if ([string]::IsNullOrWhiteSpace($hint)) { continue }
            $hintCount++

            $include = [string]$ref.GetAttribute('Include')
            $full = [IO.Path]::GetFullPath((Join-Path $project.DirectoryName $hint))
            if (Test-Path -LiteralPath $full -PathType Leaf) {
                $file = Get-Item -LiteralPath $full
                $version = 'native-or-unreadable'
                $assemblyName = $null
                $assemblyFullName = $null
                try {
                    $an = [Reflection.AssemblyName]::GetAssemblyName($full)
                    $assemblyName = $an.Name
                    $assemblyFullName = $an.FullName
                    $version = $an.Version.ToString()
                    $managed.Add([pscustomobject]@{
                        Project=$project.FullName
                        Include=$include
                        Path=$full
                        Assembly=$assemblyName
                        FullName=$assemblyFullName
                        Version=$version
                    })
                } catch {
                    "WARN $include => $hint | file exists but managed identity unreadable: $($_.Exception.Message)" | Add-Content $out
                }
                "OK   $include => $hint | resolved=$full | $($file.Length) bytes | assembly=$assemblyName | version=$version" | Add-Content $out
            } else {
                $line = "MISS $include => $hint | resolved=$full"
                $line | Add-Content $out
                $missing.Add("$($project.FullName) :: $include :: $hint :: $full")
            }
        }
    } catch {
        "XMLERR $($_.Exception.Message)" | Add-Content $out
    }
}

"`n===== Critical CAD/CAM binaries =====" | Add-Content $out
$criticalNames = @('CmdLangAPI','Newtonsoft.Json','mwInterop','mwEntities','devDept.Eyeshot.v2026','devDept.Eyeshot.Control.Win.v2026','devDept.Eyeshot.x86.v2026','buClass','buCore','buControls','buMW','buEyeBase')
foreach ($name in $criticalNames) {
    $hits = @($managed | Where-Object { $_.Assembly -eq $name -or $_.Include -like "$name*" })
    if ($hits.Count -eq 0) {
        "NOT_RESOLVED $name" | Add-Content $out
    } else {
        $versions = @($hits | Select-Object -ExpandProperty Version -Unique)
        $paths = @($hits | Select-Object -ExpandProperty Path -Unique)
        "RESOLVED $name versions=[$($versions -join ', ')] count=$($hits.Count) paths=[$($paths -join '; ')]" | Add-Content $out
    }
}

"`n===== Duplicate managed assembly versions =====" | Add-Content $out
$managed | Group-Object Assembly | Where-Object { $_.Name -and (@($_.Group.Version | Select-Object -Unique).Count -gt 1) } | ForEach-Object {
    $versions = @($_.Group.Version | Select-Object -Unique)
    "VERSION_CONFLICT $($_.Name): $($versions -join ', ')" | Add-Content $out
}

"`nHintPath references inspected: $hintCount" | Tee-Object -Append $out
"Managed HintPath references resolved: $($managed.Count)" | Tee-Object -Append $out
"Missing HintPath references: $($missing.Count)" | Tee-Object -Append $out
$missing | ForEach-Object { "  $_" | Add-Content $out }

if ($missing.Count -gt 0) { exit 2 }
